#!/usr/bin/env python3
"""Render the room broker's webhook egress from its config (factory interfaces F6, R21).

The broker's `webhooks[]` (agent-platform internal/config) names its subscribers. This script owns
infrastructure/base/room-broker/network-policy-webhooks.yaml, whole: a CiliumNetworkPolicy
`room-broker-webhooks` with egress only, one rule per subscriber:

  cluster   toEndpoints by namespace and Service name, on the URL's port
  internet  toFQDNs matchName on the URL's host, on its port (443 when it names none)

With no subscriber the egress list is `[{}]`, which selects no peer. The DNS rule `toFQDNs` needs
is in network-policy.yaml; Cilium unions the two policies.

A cluster that overrides the broker's config.yaml with its own `webhooks` gets a merge patch,
infrastructure/<cluster>/room-broker/network-policy-webhooks-patch.yaml, that its kustomization
lists under `patches`. A patch the overlay does not need, a needed one that is missing or unlisted,
or drift in either fails.

The URL rules mirror the broker's (config.go validate and validateInternet) and its dial guard's
host refusals: a `${var}` label is accepted as is, Flux substitutes this policy as it does the config.
Each cluster subscriber must name a Service, somewhere in this repository's manifests, whose selector
is its app.kubernetes.io/name.

A cluster subscriber's Service port must equal its targetPort, or have none: Cilium enforces `toPorts`
on the backend port, so a differing or named targetPort is refused rather than resolved. An overlay
whose config replaces the broker's and names no `webhooks` has no subscribers, so it gets a patch that
allows nothing when base has some. The base kustomization must list the policy.

Usage: gen-webhook-egress.py [--write] [ROOT]    (ROOT defaults to this repository)
Exit:  0 the committed files are the rendering (or --write wrote it), 1 drift or a bad config, and also
       after --write while an overlay's patch it just wrote is not yet listed by that overlay's kustomization.
"""
import copy
import difflib
import pathlib
import re
import sys
from urllib.parse import urlsplit

NAME = "room-broker-webhooks"
NAMESPACE = "agent-system"
BASE = pathlib.PurePosixPath("infrastructure/base/room-broker")
POLICY = BASE / "network-policy-webhooks.yaml"
PATCH = "network-policy-webhooks-patch.yaml"
CLUSTER_URL = re.compile(r"^https?://([a-z0-9-]+)\.([a-z0-9-]+)\.svc\.cluster\.local:([0-9]{1,5})/")
DNS_LABEL = re.compile(r"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$")  # the broker's dnsLabel (config.go)
HOST_LABEL = re.compile(r"^[a-z0-9-]+$")
# The only variable an internet host may use: Flux substitutes it in the CNP as in the config, and a
# private zone's name (private_domain_name) would admit private addresses at L3.
HOST_VARS = ("public_domain_name",)
PRIVATE_SUFFIXES = (".local", ".internal", ".svc", ".cluster.local", ".localdomain")
HEADER = """\
# Generated by scripts/ci/gen-webhook-egress.py --write from the broker's config.yaml `webhooks`
# (factory interfaces F6, R21): edit the config, never this file. test-room-broker-webhook-egress
# fails on any difference. The DNS rule toFQDNs needs is in network-policy.yaml; Cilium unions the two.
"""
SKIP_DIRS = {"node_modules", "public", "resources"}


class ConfigError(Exception):
    pass


def rule(subscriber):
    """One egress rule for one subscriber, or ConfigError."""
    at = f"webhooks {subscriber.get('name')}"
    if not isinstance(subscriber.get("name"), str) or not DNS_LABEL.match(subscriber["name"]):
        raise ConfigError(f"webhooks {subscriber.get('name')!r}: name must be a DNS label")
    network, url = subscriber.get("network"), str(subscriber.get("url"))
    if network == "cluster":
        m = CLUSTER_URL.match(url)
        if not m:
            raise ConfigError(f"{at}: a cluster subscriber's url is http(s)://<svc>.<ns>.svc.cluster.local:<port>/…")
        svc, ns, port = m.groups()
        return {"toEndpoints": [{"matchLabels": {"io.kubernetes.pod.namespace": ns, "app.kubernetes.io/name": svc}}],
                "toPorts": [{"ports": [{"port": port, "protocol": "TCP"}]}]}
    if network != "internet":
        raise ConfigError(f"{at}: network is cluster or internet")
    try:
        u = urlsplit(url)
        host, port = (u.hostname or ""), u.port
    except ValueError as e:
        raise ConfigError(f"{at}: url does not parse ({e})")
    if not host:
        raise ConfigError(f"{at}: url does not parse")
    if u.scheme != "https":
        raise ConfigError(f"{at}: an internet subscriber is https")
    host = host.rstrip(".")
    for label in host.split("."):
        var = re.fullmatch(r"\$\{([a-z_]+)\}", label)
        if var and var[1] not in HOST_VARS:
            raise ConfigError(f"{at}: ${{{var[1]}}} is not an allowed variable in an internet host ({', '.join(HOST_VARS)})")
        if not var and not HOST_LABEL.match(label):
            raise ConfigError(f"{at}: host label {label!r} holds more than a-z, 0-9 and -")
    if port == 0:
        raise ConfigError(f"{at}: port 0")
    if ":" in host or re.fullmatch(r"[0-9.]+", host):
        raise ConfigError(f"{at}: an internet subscriber's host is a DNS name, never an address")
    if host == "localhost" or "." not in host or host.endswith(PRIVATE_SUFFIXES):
        raise ConfigError(f"{at}: an internet subscriber's host is not a cluster or private name")
    return {"toFQDNs": [{"matchName": host}], "toPorts": [{"ports": [{"port": str(443 if port is None else port), "protocol": "TCP"}]}]}


def render(config):
    """The CiliumNetworkPolicy for the config's `webhooks`."""
    subscribers = (config or {}).get("webhooks") or []
    names = [s.get("name") for s in subscribers]
    for n in sorted({n for n in names if names.count(n) > 1}):
        raise ConfigError(f"webhooks {n}: duplicate name")
    return {"apiVersion": "cilium.io/v2", "kind": "CiliumNetworkPolicy",
            "metadata": {"name": NAME, "namespace": NAMESPACE},
            "spec": {"endpointSelector": {"matchLabels": {"app.kubernetes.io/name": "room-broker"}},
                     # An empty rule selects no peer: egress enforcement on, nothing allowed.
                     "egress": [rule(s) for s in subscribers] or [{}]}}


def overlay_patch(base, overlay):
    """The merge patch an overlay's own subscribers need, or None. A CRD takes a JSON merge patch,
    so spec.egress is replaced whole."""
    # An overlay's config replaces base's whole, so no `webhooks` key means no subscribers.
    if ((overlay or {}).get("webhooks") or []) == ((base or {}).get("webhooks") or []):
        return None
    full = render(overlay)
    return {"apiVersion": full["apiVersion"], "kind": full["kind"], "metadata": full["metadata"],
            "spec": copy.deepcopy(full["spec"])}


def service_error(subscriber, spec):
    """Why a cluster subscriber's Service cannot carry its rule, or None. Cilium enforces toPorts on the
    backend port, so the Service port must be the targetPort (or have none); a named one is not resolved."""
    svc, ns, port = CLUSTER_URL.match(subscriber["url"]).groups()
    at = f"Service {ns}/{svc}"
    if (spec.get("selector") or None) != {"app.kubernetes.io/name": svc}:
        return f"{at}'s selector is {spec.get('selector')}, not {{app.kubernetes.io/name: {svc}}}"
    entry = next((p for p in spec.get("ports") or [] if p.get("port") == int(port)), None)
    if entry is None:
        return f"{at} has no port {port}"
    target = entry.get("targetPort", entry["port"])
    if isinstance(target, bool) or target != int(port):
        return (f"{at}: port {port} has targetPort {target!r}; Cilium enforces toPorts on the backend port, "
                f"so targetPort must be the number {port} or absent")
    return None


def dump(doc, yaml, header=HEADER):
    return header + "---\n" + yaml.safe_dump(doc, sort_keys=False)


def services(root, yaml):
    """{(namespace, name): {selector, ports}} for every Service among the repository's manifests."""
    out = {}
    for path in sorted(root.rglob("*.yaml")):
        rel = path.relative_to(root).parts
        if any(p.startswith(".") or p in SKIP_DIRS for p in rel[:-1]):
            continue
        try:
            docs = list(yaml.safe_load_all(path.read_text()))
        except yaml.YAMLError:
            continue  # a template or a values file, not a manifest
        for d in docs:
            if isinstance(d, dict) and d.get("kind") == "Service" and isinstance(d.get("metadata"), dict):
                spec = d.get("spec") or {}
                out[(d["metadata"].get("namespace"), d["metadata"].get("name"))] = {
                    "selector": spec.get("selector"), "ports": spec.get("ports") or []}
    return out


def main(argv):
    import yaml  # here only: the unit suite imports this module without PyYAML

    args = argv[1:]
    write = "--write" in args
    paths = [a for a in args if a != "--write"]
    root = pathlib.Path(paths[0]) if paths else pathlib.Path(__file__).resolve().parents[2]
    errors, late, wanted = [], [], {}
    base = yaml.safe_load((root / BASE / "config.yaml").read_text()) or {}
    configs = {"base": base}
    try:
        wanted[POLICY.as_posix()] = dump(render(base), yaml)
    except ConfigError as e:
        errors.append(f"{BASE}/config.yaml: {e}")
    base_kustomization = yaml.safe_load((root / BASE / "kustomization.yaml").read_text()) or {}
    if POLICY.name not in (base_kustomization.get("resources") or []):
        errors.append(f"{BASE}/kustomization.yaml: must list {POLICY.name} under resources")
    overlays = sorted(p for p in (root / "infrastructure").glob("*/room-broker") if p.parent.name != "base")
    for d in overlays:
        rel = d.relative_to(root)
        patch_file, kustomization = d / PATCH, d / "kustomization.yaml"
        patch = None
        if (d / "config.yaml").exists():
            overlay = yaml.safe_load((d / "config.yaml").read_text()) or {}
            configs[rel.as_posix()] = overlay
            try:
                patch = overlay_patch(base, overlay)
            except ConfigError as e:
                errors.append(f"{rel}/config.yaml: {e}")
                continue
        listed = any(isinstance(p, dict) and p.get("path") == PATCH
                     for p in (yaml.safe_load(kustomization.read_text()) or {}).get("patches") or []) if kustomization.exists() else False
        if patch is not None:
            wanted[(rel / PATCH).as_posix()] = dump(patch, yaml)
            if not listed:
                late.append(f"{rel}/kustomization.yaml: must list `- path: {PATCH}` under patches, its config holds subscribers base's does not")
        else:
            if patch_file.exists():
                late.append(f"{rel}/{PATCH}: this overlay needs no patch (its subscribers are base's); remove it")
            if listed:
                late.append(f"{rel}/kustomization.yaml: lists {PATCH}, which this overlay does not need")
    if not errors:
        have = services(root, yaml)
        for where, cfg in configs.items():
            for s in (cfg.get("webhooks") or []):
                if s.get("network") != "cluster":
                    continue
                svc, ns, _ = CLUSTER_URL.match(s["url"]).groups()
                spec = have.get((ns, svc))
                if spec is None:
                    errors.append(f"{where} webhooks {s['name']}: no Service {ns}/{svc} among this repository's manifests")
                elif (why := service_error(s, spec)):
                    errors.append(f"{where} webhooks {s['name']}: {why}")
    for e in errors:
        print(f"FAIL {e}", file=sys.stderr)
    if errors:
        return 1
    drift = False
    for path, text in wanted.items():
        target = root / path
        current = target.read_text() if target.exists() else ""
        if text == current:
            print(f"gen-webhook-egress: {path} is its config's rendering")
        elif write:
            target.write_text(text)
            print(f"gen-webhook-egress: wrote {path}")
        else:
            drift = True
            sys.stderr.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True),
                                                       f"{path} (committed)", f"{path} (rendered from config.yaml)"))
            print(f"FAIL {path} differs from its config's rendering: edit config.yaml, run "
                  "python3 scripts/ci/gen-webhook-egress.py --write and commit both", file=sys.stderr)
    # Reported after the files are written, so --write can create a patch before its kustomization lists it.
    for e in late:
        print(f"FAIL {e}", file=sys.stderr)
    return 1 if drift or late else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
